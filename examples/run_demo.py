"""Run a scripted session offline and print an execution trace.

Usage:  python examples/run_demo.py > examples/sample_session.md
Runs without a Gemini key (local fallback mode) so anyone can reproduce it.
"""
import json
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.environ.pop("GEMINI_API_KEY", None)
random.seed(7)  # reproducible problem choice

from graph import create_thread_id, get_debug, get_profile, get_thread, pending_approval, resume, send_message  # noqa: E402

STEPS = [
    ("say", "Hi, my name is Rahul. I prefer Java."),
    ("approve", True),
    ("say", "Let's practice linked list."),
    ("say", "Give me a hint."),
    ("say", "I think I can use two pointers, a slow one and a fast one."),
    ("say", "What is the time complexity?"),
]

thread = create_thread_id()
print("# Sample CodeCoach session (execution trace)\n")
print("Generated by `python examples/run_demo.py` in local fallback mode (no Gemini key).\n")
for i, (kind, value) in enumerate(STEPS, 1):
    if kind == "say":
        print(f"## Turn {i}\n\n**User:** {value}\n")
        send_message(thread, value)
    else:
        print(f"## Turn {i}: human approval\n\n**User clicks:** {'✅ Approve' if value else '❌ Reject'}\n")
        resume(thread, value)
    d = get_debug(thread)
    print(f"- **Route:** `{d.get('route')}`")
    for call in d.get("tool_calls", []) if kind == "say" else []:
        print(f"- **Tool call:** `{json.dumps(call, ensure_ascii=False)}`")
    if d.get("pending_profile") and kind == "say":
        print(f"- **Paused for approval:** `{json.dumps(pending_approval(thread), ensure_ascii=False)}`")
    print(f"\n**CodeCoach:**\n\n> " + get_thread(thread)[-1]["content"].replace("\n", "\n> ") + "\n")

print(f"## Final long-term profile\n\n```json\n{json.dumps(get_profile(), indent=2)}\n```")
